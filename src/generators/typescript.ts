export interface TypeScriptGeneratorOptions {
  emitTypes?: boolean;
  emitClient?: boolean;
  emitValidators?: boolean;
  emitProgram?: boolean;
  contractYaml?: string;
}

export interface TypeScriptOutput {
  [filename: string]: string;
}

export function generateTypeScript(
  ctx: NormalizedContext,
  options: TypeScriptGeneratorOptions = {},
): TypeScriptOutput {
  const {
    emitTypes = true,
    emitClient = true,
    emitValidators = true,
    emitProgram = true,
    contractYaml,
  } = options;

  const hasEffects = contextHasEffects(ctx);
  const hasExtract = contractYaml !== undefined;

  const output: TypeScriptOutput = {
    "index.ts": generateIndex(ctx, { emitProgram, hasEffects, hasExtract }),
    "types.ts": emitTypes ? generateTypes(ctx) : "// types generation disabled\nexport {};\n",
    "commands.ts": emitClient ? generateCommands(ctx) : "// client generation disabled\nexport {};\n",
    "schemas.ts": emitValidators ? generateSchemas(ctx) : "// validators generation disabled\nexport {};\n",
  };

  if (emitProgram) {
    output["program.ts"] = generateProgram(ctx, buildProgramModel(ctx, contractYaml !== undefined));
  }

  if (hasExtract && contractYaml) {
    output["contract.ts"] = generateContractModule(ctx, contractYaml);
  }

  if (hasEffects) {
    output["policy.ts"] = generatePolicyModule(ctx);
    output["policy-runtime.ts"] = loadPolicyRuntime();
  }

  return output;
}

function generateIndex(
  ctx: NormalizedContext,
  opts: { emitProgram: boolean; hasEffects: boolean; hasExtract: boolean },
): string {
  const lines: string[] = [];
  lines.push("// Auto-generated by cli-contracts. Do not edit.");
  lines.push('export * from "./types.js";');
  lines.push('export * from "./commands.js";');
  lines.push('export * from "./schemas.js";');
  if (opts.emitProgram) {
    lines.push('export { createProgram } from "./program.js";');
    lines.push('export type { CommandHandlers, ProgramOptions } from "./program.js";');
  }
  if (opts.hasEffects) {
    lines.push('export { commandDefinitions, deriveCommandPolicy } from "./policy.js";');
  }
  if (opts.hasExtract) {
    lines.push('export { CONTRACT_YAML, CONTRACT_JSON_STR } from "./contract.js";');
  }
  lines.push("");
  return lines.join("\n");
}

function generateTypes(ctx: NormalizedContext): string {
  const lines: string[] = [];
  lines.push("// Auto-generated by cli-contracts. Do not edit.");
  lines.push("");

  for (const cs of ctx.command_sets) {
    for (const cmd of cs.commands) {
      generateCommandTypes(cmd, cs, lines, ctx.components);
    }
  }

  if (ctx.components.schemas) {
    for (const [name, schema] of Object.entries(ctx.components.schemas)) {
      generateSchemaType(identifier(name, name), schema, lines);
    }
  }

  return lines.join("\n");
}

function generateCommandTypes(
  cmd: NormalizedCommand,
  cs: NormalizedCommandSet,
  lines: string[],
  components: Components,
): void {
  const prefix = commandTypeName(cmd);

  // Arguments type
  if (cmd.arguments.length > 0) {
    lines.push(`export interface ${prefix}Args {`);
    for (const arg of cmd.arguments) {
      const optional = arg.required ? "" : "?";
      const tsType = arg.variadic ? "string[]" : jsonSchemaToTs(arg.schema);
      lines.push(`  ${propertyName(toCamelCase(arg.name))}${optional}: ${tsType};`);
    }
    lines.push("}");
    lines.push("");
  }

  // Options type
  if (cmd.options.length > 0) {
    lines.push(`export interface ${prefix}Options {`);
    for (const opt of cmd.options) {
      const optional = opt.required ? "" : "?";
      // A repeatable option is given once for each of its values.
      const item = schemaType(opt.schema);
      const tsType = typeToTs(optionTakesManyValues(opt) ? { kind: "array", items: item } : item);
      lines.push(`  ${propertyName(optionFlags(opt).key)}${optional}: ${tsType};`);
    }
    lines.push("}");
    lines.push("");
  }

  if (cmd.exits.length > 0) {
    const exitCodes = cmd.exits.map((e) => e.exit_code);
    lines.push(`export type ${prefix}ExitCode = ${exitCodes.join(" | ")};`);
    lines.push("");

    const resultVariants: string[] = [];
    for (const exit of cmd.exits) {
      const variant = buildExitResultVariant(exit, prefix, components);
      resultVariants.push(variant);
    }
    lines.push(`export type ${prefix}ExitResult =`);
    lines.push(`  ${resultVariants.join("\n  | ")};`);
    lines.push("");
  }
}

function buildExitResultVariant(
  exit: NormalizedExit,
  prefix: string,
  components: Components,
): string {
  const parts: string[] = [`exitCode: ${exit.exit_code}`];

  if (exit.stdout) {
    const type = resolveOutputType(exit.stdout.schema, components);
    const opt = exit.stdout.required === false ? "?" : "";
    parts.push(`stdout${opt}: ${type}`);
  }

  if (exit.stderr) {
    const type = resolveOutputType(exit.stderr.schema, components);
    const opt = exit.stderr.required === false ? "?" : "";
    parts.push(`stderr${opt}: ${type}`);
  }

  return `{ ${parts.join("; ")} }`;
}

function resolveOutputType(
  schema: JsonSchema | undefined,
  components: Components,
): string {
  if (!schema) return "unknown";
  if (schema.$ref) {
    const name = refToTypeName(schema.$ref);
    return name;
  }
  return jsonSchemaToTs(schema);
}

function generateCommands(ctx: NormalizedContext): string {
  const lines: string[] = [];
  lines.push("// Auto-generated by cli-contracts. Do not edit.");
  lines.push('import { execFile } from "node:child_process";');
  lines.push('import { promisify } from "node:util";');
  lines.push("");
  lines.push("const execFileAsync = promisify(execFile);");
  lines.push("");

  lines.push("export interface ExecResult {");
  lines.push("  exitCode: number;");
  lines.push("  stdout: string;");
  lines.push("  stderr: string;");
  lines.push("}");
  lines.push("");

  for (const cs of ctx.command_sets) {
    for (const cmd of cs.commands) {
      generateCommandFunction(cmd, cs, lines);
    }
  }

  return lines.join("\n");
}

function generateCommandFunction(
  cmd: NormalizedCommand,
  cs: NormalizedCommandSet,
  lines: string[],
): void {
  const funcName = identifier(toCamelCase(cmd.full_id), cmd.full_id);
  const prefix = commandTypeName(cmd);
  const hasArgs = cmd.arguments.length > 0;
  const hasOpts = cmd.options.length > 0;

  const params: string[] = ["executable: string"];
  if (hasArgs) params.push(`args: import("./types.js").${prefix}Args`);
  if (hasOpts) params.push(`options?: Partial<import("./types.js").${prefix}Options>`);

  lines.push(`export async function ${funcName}(`);
  lines.push(`  ${params.join(",\n  ")},`);
  lines.push(`): Promise<ExecResult> {`);
  lines.push(`  const cmdArgs: string[] = ${JSON.stringify(cmd.path)};`);

  if (hasArgs) {
    for (const arg of cmd.arguments) {
      const value = propertyAccess("args", toCamelCase(arg.name));
      if (arg.variadic) {
        lines.push(`  if (${value}) cmdArgs.push(...${value});`);
      } else {
        lines.push(`  if (${value} !== undefined) cmdArgs.push(String(${value}));`);
      }
    }
  }

  if (hasOpts) {
    lines.push("  if (options) {");
    for (const opt of cmd.options) {
      const { long, negated, key } = optionFlags(opt);
      const value = propertyAccess("options", key);
      const longFlag = JSON.stringify(long);
      if (negated) {
        lines.push(`    if (${value} !== undefined) cmdArgs.push(${value} ? ${longFlag} : ${JSON.stringify(negated)});`);
      } else if (opt.schema?.type === "boolean") {
        lines.push(`    if (${value}) cmdArgs.push(${longFlag});`);
      } else if (optionTakesManyValues(opt)) {
        lines.push(`    if (${value} !== undefined) for (const v of ${value}) cmdArgs.push(${longFlag}, String(v));`);
      } else {
        lines.push(`    if (${value} !== undefined) cmdArgs.push(${longFlag}, String(${value}));`);
      }
    }
    lines.push("  }");
  }

  lines.push("");
  lines.push("  try {");
  lines.push("    const result = await execFileAsync(executable, cmdArgs);");
  lines.push("    return { exitCode: 0, stdout: result.stdout, stderr: result.stderr };");
  lines.push("  } catch (err: unknown) {");
  lines.push("    const e = err as { code?: number; stdout?: string; stderr?: string };");
  lines.push("    return {");
  lines.push("      exitCode: typeof e.code === 'number' ? e.code : 1,");
  lines.push("      stdout: e.stdout ?? '',");
  lines.push("      stderr: e.stderr ?? '',");
  lines.push("    };");
  lines.push("  }");
  lines.push("}");
  lines.push("");
}

function generateSchemas(ctx: NormalizedContext): string {
  const lines: string[] = [];
  lines.push("// Auto-generated by cli-contracts. Do not edit.");
  lines.push("");

  if (!ctx.components.schemas || Object.keys(ctx.components.schemas).length === 0) {
    lines.push("export {};");
    lines.push("");
    return lines.join("\n");
  }

  lines.push("export const schemas = {");
  for (const [name, schema] of Object.entries(ctx.components.schemas)) {
    lines.push(`  ${propertyName(name)}: ${JSON.stringify(schema, null, 2).replace(/\n/g, "\n  ")},`);
  }
  lines.push("} as const;");
  lines.push("");

  for (const cs of ctx.command_sets) {
    for (const cmd of cs.commands) {
      const exitCodes = cmd.exits.map((e) => e.exit_code);
      const constName = identifier(`${toCamelCase(cmd.id)}ExitCodes`, cmd.id);
      lines.push(`export const ${constName} = [${exitCodes.join(", ")}] as const;`);
    }
  }
  lines.push("");

  return lines.join("\n");
}

function generateSchemaType(
  name: string,
  schema: JsonSchema,
  lines: string[],
): void {
  if (schema.allOf) {
    generateAllOfSchemaType(name, schema.allOf, lines);
  } else if (schema.type === "object" && schema.properties) {
    lines.push(`export interface ${name} {`);
    const required = new Set(schema.required ?? []);
    for (const [prop, propSchema] of Object.entries(schema.properties)) {
      const opt = required.has(prop) ? "" : "?";
      const tsType = jsonSchemaToTs(propSchema);
      lines.push(`  ${propertyName(prop)}${opt}: ${tsType};`);
    }
    lines.push("}");
    lines.push("");
  } else if (schema.type === "array" && schema.items) {
    lines.push(`export type ${name} = ${jsonSchemaToTs(schema.items)}[];`);
    lines.push("");
  } else if (schema.enum) {
    const values = schema.enum.map((v) =>
      typeof v === "string" ? JSON.stringify(v) : String(v),
    );
    lines.push(`export type ${name} = ${values.join(" | ")};`);
    lines.push("");
  } else {
    lines.push(`export type ${name} = ${jsonSchemaToTs(schema)};`);
    lines.push("");
  }
}

function generateAllOfSchemaType(
  name: string,
  allOf: JsonSchema[],
  lines: string[],
): void {
  const bases: string[] = [];
  const ownProps = new Map<string, { optional: boolean; tsTypes: string[] }>();

  for (const sub of allOf) {
    if (sub.$ref) {
      bases.push(refToTypeName(sub.$ref));
    } else if (sub.type === "object" && sub.properties) {
      const required = new Set(sub.required ?? []);
      for (const [key, propSchema] of Object.entries(sub.properties)) {
        const tsType = jsonSchemaToTs(propSchema);
        const merged = ownProps.get(key);
        if (!merged) {
          ownProps.set(key, { optional: !required.has(key), tsTypes: [tsType] });
          continue;
        }
        // Every allOf branch has to hold at once, so a property required by
        // any branch is required and differing types intersect.
        merged.optional = merged.optional && !required.has(key);
        if (!merged.tsTypes.includes(tsType)) merged.tsTypes.push(tsType);
      }
    } else {
      bases.push(jsonSchemaToTs(sub));
    }
  }

  if (ownProps.size > 0) {
    const extendsClause = bases.length > 0 ? ` extends ${bases.join(", ")}` : "";
    lines.push(`export interface ${name}${extendsClause} {`);
    for (const [key, prop] of ownProps) {
      const opt = prop.optional ? "?" : "";
      const tsType =
        prop.tsTypes.length === 1
          ? prop.tsTypes[0]
          : prop.tsTypes.map((t) => `(${t})`).join(" & ");
      lines.push(`  ${propertyName(key)}${opt}: ${tsType};`);
    }
    lines.push("}");
    lines.push("");
  } else if (bases.length > 0) {
    lines.push(`export type ${name} = ${bases.join(" & ")};`);
    lines.push("");
  } else {
    lines.push(`export type ${name} = unknown;`);
    lines.push("");
  }
}

function jsonSchemaToTs(schema?: JsonSchema): string {
  return typeToTs(schemaType(schema));
}

/** A type TypeScript writes with `|` or `&`. */
function isCompound(type: TypeExpr): boolean {
  return (
    ((type.kind === "union" || type.kind === "intersection") && type.members.length > 1) ||
    (type.kind === "literals" && type.values.length > 1)
  );
}

function typeToTs(type: TypeExpr): string {
  switch (type.kind) {
    case "unknown":
      return "unknown";
    case "ref":
      return identifier(type.name, type.name);
    case "union":
      return type.members.map(typeToTs).join(" | ");
    case "intersection":
      return type.members.map(typeToTs).join(" & ");
    case "literals":
      return type.values.map((v) => (typeof v === "string" ? JSON.stringify(v) : String(v))).join(" | ");
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      // An element type of several members is parenthesized: `("a" | "b")[]`.
      return isCompound(type.items) ? `(${typeToTs(type.items)})[]` : `${typeToTs(type.items)}[]`;
    case "object":
      return `{ ${type.fields.map((f) => `${propertyName(f.name)}${f.optional ? "?" : ""}: ${typeToTs(f.type)}`).join("; ")} }`;
    case "map":
      return "Record<string, unknown>";
  }
}

function refToTypeName(ref: string): string {
  const parts = ref.split("/");
  const name = parts[parts.length - 1];
  return identifier(name, name);
}

// An id or name as an identifier: its `.`-, `-`- and `_`-separated words
// joined by the same camelCase rule as an option's key.
export function toPascalCase(str: string): string {
  const camel = camelCase(str.replace(/[._]/g, "-"));
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

export function toCamelCase(str: string): string {
  const camel = camelCase(str.replace(/[._]/g, "-"));
  return camel.charAt(0).toLowerCase() + camel.slice(1);
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** A key as a property name in an object type. */
function propertyName(key: string): string {
  return IDENTIFIER.test(key) ? key : JSON.stringify(key);
}

/** An expression that reads `key` from `object`. */
function propertyAccess(object: string, key: string): string {
  return IDENTIFIER.test(key) ? `${object}.${key}` : `${object}[${JSON.stringify(key)}]`;
}

const JS_RESERVED = new Set([
  "break", "case", "catch", "class", "const", "continue", "debugger",
  "default", "delete", "do", "else", "export", "extends", "false",
  "finally", "for", "function", "if", "import", "in", "instanceof",
  "let", "new", "null", "return", "super", "switch", "this", "throw",
  "true", "try", "typeof", "undefined", "var", "void", "while", "with",
  "yield", "enum", "await", "implements", "interface", "package",
  "private", "protected", "public", "static",
]);

function safeIdentifier(name: string): string {
  const camel = toCamelCase(name);
  return identifier(JS_RESERVED.has(camel) ? `${camel}Arg` : camel, name);
}

/** A TypeScript identifier, Unicode letters included. */
const TS_IDENTIFIER = /^[\p{ID_Start}$_][\p{ID_Continue}$‌‍]*$/u;

/**
 * The name the generated source declares (a type, function, parameter or
 * variable) for a contract name. It is written into the source as code, so a
 * contract name that does not give an identifier fails the generation.
 */
function identifier(name: string, contractName: string): string {
  if (TS_IDENTIFIER.test(name) && !JS_RESERVED.has(name)) return name;
  throw new Error(
    `Cannot generate TypeScript: ${JSON.stringify(contractName)} is not a TypeScript identifier (as ${JSON.stringify(name)})`,
  );
}

/** The prefix of the types generated for a command. */
function commandTypeName(cmd: NormalizedCommand): string {
  return identifier(toPascalCase(cmd.id), cmd.id);
}

