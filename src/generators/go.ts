import type { NormalizedContext } from "../types.js";
import { buildRuntimeSpec, type RuntimeSpec, type SpecCommand } from "./runtime-spec.js";
import type { TreeNode, TreeOption } from "./commander-tree.js";
import { toPascalCase, toCamelCase } from "./typescript.js";
import { buildTypeModel, type Decl, type Field, type TypeExpr, type TypeModel } from "./type-model.js";

// The Go program of a contract: the command tree and handler interface for the
// runtime github.com/foo-log-inc/cli-contracts/go/cli_contracts_runtime, which
// parses an invocation by commander's rules. Everything here is rendered from
// the runtime spec (runtime-spec.ts); nothing is decided here.

export const GO_RUNTIME_IMPORT = "github.com/foo-log-inc/cli-contracts/go/cli_contracts_runtime";

export interface GoGeneratorOptions {
  /** The Go package name of the generated files. */
  package: string;
  contractYaml?: string;
}

const GO_KEYWORDS = new Set([
  "break", "case", "chan", "const", "continue", "default", "defer", "else", "fallthrough",
  "for", "func", "go", "goto", "if", "import", "interface", "map", "package", "range",
  "return", "select", "struct", "switch", "type", "var",
]);

const GO_IDENTIFIER = /^[\p{L}_][\p{L}\p{Nd}_]*$/u;

/** A Go identifier for a contract name; a name that does not give one fails the generation. */
export function goIdentifier(name: string, contractName: string): string {
  if (GO_IDENTIFIER.test(name) && !GO_KEYWORDS.has(name)) return name;
  throw new Error(
    `Cannot generate Go: ${JSON.stringify(contractName)} is not a Go identifier (as ${JSON.stringify(name)})`,
  );
}

/** The exported Go name of a contract id or key. */
export function goExported(name: string): string {
  const pascal = toPascalCase(name);
  return goIdentifier(pascal.charAt(0).toUpperCase() + pascal.slice(1), name);
}

/** A Go parameter name for an argument. */
export function goParam(name: string): string {
  const camel = toCamelCase(name);
  return goIdentifier(GO_KEYWORDS.has(camel) ? `${camel}Arg` : camel, name);
}

/** A Go string literal. JSON's escapes are Go's. */
export function goString(s: string): string {
  return JSON.stringify(s);
}

/** A JSON value as a Go literal of the runtime's Value. */
export function goValue(v: unknown, indent: string): string {
  if (v === null || v === undefined) return "nil";
  if (typeof v === "boolean") return String(v);
  if (typeof v === "number") {
    const text = JSON.stringify(v);
    return text === "null" ? "nil" : `rt.Number(${goString(text)})`;
  }
  if (typeof v === "string") return goString(v);
  const inner = indent + "\t";
  if (Array.isArray(v)) {
    if (v.length === 0) return "[]rt.Value{}";
    return `[]rt.Value{\n${v.map((item) => `${inner}${goValue(item, inner)},`).join("\n")}\n${indent}}`;
  }
  const entries = Object.entries(v as Record<string, unknown>).filter(([, value]) => value !== undefined);
  if (entries.length === 0) return "rt.NewObject()";
  return `rt.Obj(\n${entries.map(([k, value]) => `${inner}${goString(k)}, ${goValue(value, inner)},`).join("\n")}\n${indent})`;
}

function goStrings(items: string[]): string {
  return `[]string{${items.map(goString).join(", ")}}`;
}

const HEADER = "// Code generated by cli-contracts. DO NOT EDIT.\n";

/** The type of the handler's options of a command. */
function handlerOptionsType(cmd: SpecCommand): string {
  return `${goExported(cmd.id)}HandlerOptions`;
}

function handlerOptionField(type: SpecCommand["options"][number]["type"]): string {
  return type === "boolean" ? "*bool" : type === "strings" ? "[]string" : "*string";
}

function handlerSignature(cmd: SpecCommand): string {
  const params = cmd.arguments.map((arg) => {
    const type = arg.variadic ? "[]string" : arg.required ? "string" : "*string";
    return `${goParam(arg.name)} ${type}`;
  });
  params.push(`options ${handlerOptionsType(cmd)}`, "parentOpts *rt.Object");
  return `${goExported(cmd.id)}(${params.join(", ")}) ${cmd.llm ? "(int, *string)" : "int"}`;
}

function renderHandler(cmd: SpecCommand, indent: string): string {
  const args = cmd.arguments.map((arg, i) =>
    arg.variadic ? `inv.Args[${i}].Values` : arg.required ? `inv.Args[${i}].Value` : `inv.Args[${i}].Optional()`,
  );
  const fields = cmd.options.map((opt) => {
    const accessor = opt.type === "boolean" ? "Bool" : opt.type === "strings" ? "Strings" : "String";
    return `${goExported(opt.key)}: inv.Opts.${accessor}(${goString(opt.key)})`;
  });
  args.push(`${handlerOptionsType(cmd)}{${fields.join(", ")}}`, "inv.Globals");
  const call = `h.${goExported(cmd.id)}(${args.join(", ")})`;
  const i2 = indent + "\t";
  return cmd.llm
    ? `func(inv *rt.Invocation) rt.Outcome {\n${i2}code, prompt := ${call}\n${i2}return rt.Outcome{ExitCode: code, Prompt: prompt}\n${indent}}`
    : `func(inv *rt.Invocation) rt.Outcome {\n${i2}return rt.Outcome{ExitCode: ${call}}\n${indent}}`;
}

function renderOption(opt: TreeOption): string {
  const fields = [`Flags: ${goString(opt.flags)}`];
  if (opt.short !== undefined) fields.push(`Short: ${goString(opt.short)}`);
  if (opt.long !== undefined) fields.push(`Long: ${goString(opt.long)}`);
  fields.push(`Name: ${goString(opt.name)}`, `Key: ${goString(opt.key)}`);
  fields.push(`Kind: rt.${opt.kind === "flag" ? "Flag" : opt.kind === "negate" ? "Negate" : "TakesValue"}`);
  if (opt.variadic) fields.push("Variadic: true");
  if (opt.version) fields.push("Version: true");
  return `{${fields.join(", ")}}`;
}

// A command as a call of the runtime's Cmd. Calls, unlike keyed literals, are
// not column-aligned by gofmt, so the output is gofmt's as written.
function renderNode(node: TreeNode, commands: Map<string, SpecCommand>, indent: string): string {
  const i1 = indent + "\t";
  const parts: string[] = [];
  if (node.options.length > 0) {
    parts.push(`rt.Options(\n${node.options.map((o) => `${i1}\t&rt.Option${renderOption(o)},`).join("\n")}\n${i1})`);
  }
  if (node.initialValues.length > 0) {
    parts.push(
      `rt.Initial(${node.initialValues.map(([k, v]) => `${goString(k)}, ${Array.isArray(v) ? goStrings(v) : goValue(v, i1)}`).join(", ")})`,
    );
  }
  if (node.arguments.length > 0) {
    parts.push(
      `rt.Arguments(${node.arguments
        .map((a) => `rt.Argument{Name: ${goString(a.name)}${a.required ? ", Required: true" : ""}${a.variadic ? ", Variadic: true" : ""}}`)
        .join(", ")})`,
    );
  }
  if (node.commands.length > 0) {
    parts.push(
      `rt.Subcommands(\n${node.commands.map((c) => `${i1}\t${renderNode(c, commands, i1 + "\t")},`).join("\n")}\n${i1})`,
    );
  }
  if (node.hidden) parts.push("rt.Hidden()");
  if (node.defaultCommand !== undefined) parts.push(`rt.DefaultSubcommand(${goString(node.defaultCommand)})`);
  if (node.helpCommand !== undefined) parts.push(`rt.ImplicitHelpCommand(${goString(node.helpCommand)})`);
  if (node.helpShort !== undefined || node.helpLong !== undefined) {
    parts.push(`rt.HelpFlags(${goString(node.helpShort ?? "")}, ${goString(node.helpLong ?? "")})`);
  }
  if (node.action?.kind === "extract") {
    parts.push("rt.RunsBuiltinExtract()");
  } else if (node.action) {
    const cmd = commands.get(node.action.commandId)!;
    parts.push(
      `rt.RunsCommand(${goString(cmd.id)}, ${node.action.llm}, ${node.action.introspect}, ${renderHandler(cmd, i1)})`,
    );
  }
  if (node.optionSuggestions.length > 0 || node.commandSuggestions.length > 0) {
    parts.push(`rt.Suggestions(${goStrings(node.optionSuggestions)}, ${goStrings(node.commandSuggestions)})`);
  }
  if (node.digitShortOption) parts.push("rt.DigitShortOptions()");
  const head = `rt.Cmd(${goString(node.name)}, ${goString(node.help)}`;
  if (parts.length === 0) return `${head})`;
  return `${head},\n${parts.map((p) => `${i1}${p},`).join("\n")}\n${indent})`;
}

/** Struct fields (name, type and an optional tag), their columns aligned as gofmt aligns them. */
function goFields(fields: Array<[string, string] | [string, string, string]>): string[] {
  const nameWidth = Math.max(0, ...fields.map((f) => f[0].length));
  const typeWidth = Math.max(0, ...fields.map((f) => (f.length === 3 ? f[1].length : 0)));
  return fields.map((f) =>
    f.length === 3 ? `\t${f[0].padEnd(nameWidth)} ${f[1].padEnd(typeWidth)} ${f[2]}` : `\t${f[0].padEnd(nameWidth)} ${f[1]}`,
  );
}

function generateProgram(spec: RuntimeSpec, pkg: string): string {
  const commands = new Map(spec.commands.map((cmd) => [cmd.id, cmd]));
  const lines: string[] = [HEADER, `package ${pkg}`, "", `import rt ${goString(GO_RUNTIME_IMPORT)}`, ""];

  for (const cmd of spec.commands) {
    lines.push(`// ${handlerOptionsType(cmd)} are the options the program passes to the ${cmd.id} handler, as given.`);
    lines.push(`type ${handlerOptionsType(cmd)} struct {`);
    lines.push(...goFields(cmd.options.map((opt) => [goExported(opt.key), handlerOptionField(opt.type)])));
    lines.push("}", "");
  }

  lines.push("// CommandHandlers run the contract's commands. A handler returns the exit code;");
  lines.push("// a command that takes --adapter also returns the prompt it built, which the");
  lines.push("// program writes with --show-prompt.");
  lines.push("type CommandHandlers interface {");
  for (const cmd of spec.commands) lines.push(`\t${handlerSignature(cmd)}`);
  lines.push("}", "");

  lines.push("// NewProgram creates the program. version is what --version writes.");
  lines.push("func NewProgram(handlers CommandHandlers, version string, options rt.ProgramOptions) *rt.Program {");
  lines.push(
    `\treturn rt.NewProgram(newTree(handlers), version, options, ${spec.policyDefinitions ? "commandDefinitions()" : "nil"}, ${spec.extract ? "extractSpec" : "nil"})`,
  );
  lines.push("}", "");

  lines.push("func newTree(h CommandHandlers) *rt.Command {");
  lines.push(`\treturn ${renderNode(spec.tree, commands, "\t")}`);
  lines.push("}", "");

  if (spec.extract) {
    const x = spec.extract;
    lines.push("var extractSpec = rt.NewExtractSpec(");
    for (const text of [x.yamlWithMeta, x.yamlWithoutMeta, x.jsonWithMeta, x.jsonWithoutMeta, x.filter.head, x.filter.tail]) {
      lines.push(`\t${goString(text)},`);
    }
    for (const set of x.filter.sets) {
      lines.push(`\trt.NewExtractSet(${goString(set.id)}, ${goString(set.key)}, ${goStrings(set.before)}, ${goStrings(set.after)},`);
      for (const c of set.commands) lines.push(`\t\t${goString(c.id)}, ${goString(c.text)},`);
      lines.push("\t),");
    }
    lines.push(")", "");
  }
  return lines.join("\n");
}

function generatePolicy(spec: RuntimeSpec, pkg: string): string {
  const lines: string[] = [HEADER, `package ${pkg}`, "", 'import (', '\t"fmt"', "", `\trt ${goString(GO_RUNTIME_IMPORT)}`, ")", ""];
  lines.push("// commandDefinitions holds, by command id, the part of each command's contract");
  lines.push("// its policy is derived from.");
  lines.push("func commandDefinitions() map[string]rt.Value {");
  lines.push("\tdefinitions := map[string]rt.Value{}");
  for (const [id, def] of spec.policyDefinitions!) {
    lines.push(`\tdefinitions[${goString(id)}] = ${goValue(def, "\t")}`);
  }
  lines.push("\treturn definitions", "}", "");
  lines.push("// CommandDefinitions returns, by command id, the part of each command's contract");
  lines.push("// its policy is derived from.");
  lines.push("func CommandDefinitions() map[string]rt.Value {");
  lines.push("\treturn commandDefinitions()");
  lines.push("}", "");
  lines.push("// DeriveCommandPolicy derives a command's policy from its option values, keyed");
  lines.push("// as the program keys them (dry-run -> dryRun).");
  lines.push("func DeriveCommandPolicy(commandID string, optionValues *rt.Object) (*rt.Object, error) {");
  lines.push("\tdefinition, ok := commandDefinitions()[commandID]");
  lines.push("\tif !ok {");
  lines.push('\t\treturn nil, fmt.Errorf("Unknown command: %s", commandID)');
  lines.push("\t}");
  lines.push("\treturn rt.Introspect(commandID, definition, optionValues), nil");
  lines.push("}", "");
  return lines.join("\n");
}

function generateContract(spec: RuntimeSpec, pkg: string): string {
  return [
    HEADER,
    `package ${pkg}`,
    "",
    "// ContractYAML is the contract the program was generated from.",
    `const ContractYAML = ${goString(spec.contract!.yaml)}`,
    "",
    "// ContractJSON is the contract as JSON.",
    `const ContractJSON = ${goString(spec.contract!.json)}`,
    "",
  ].join("\n");
}

export function generateGo(ctx: NormalizedContext, options: GoGeneratorOptions): Record<string, string> {
  const pkg = goIdentifier(options.package, options.package);
  const spec = buildRuntimeSpec(ctx, options.contractYaml);
  const model = buildTypeModel(ctx);
  const output: Record<string, string> = {
    "program.go": generateProgram(spec, pkg),
    "types.go": generateGoTypes(model, pkg),
    "commands.go": generateGoCommands(model, pkg),
    "schemas.go": generateGoSchemas(model, pkg),
  };
  if (spec.policyDefinitions) output["policy.go"] = generatePolicy(spec, pkg);
  if (spec.contract) output["contract.go"] = generateContract(spec, pkg);
  return output;
}

