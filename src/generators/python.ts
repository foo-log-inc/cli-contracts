import type { NormalizedContext } from "../types.js";
import { buildRuntimeSpec, type RuntimeSpec, type SpecCommand } from "./runtime-spec.js";
import type { TreeNode, TreeOption } from "./commander-tree.js";
import { toCamelCase, toPascalCase } from "./typescript.js";
import { buildTypeModel, type Field, type TypeExpr, type TypeModel } from "./type-model.js";

// The Python program of a contract: the command tree, handler protocol and
// dispatch for the runtime package cli_contracts_runtime, which parses an
// invocation by commander's rules. Everything here is rendered from the
// runtime spec (runtime-spec.ts); nothing is decided here.

export interface PythonGeneratorOptions {
  contractYaml?: string;
}

const PYTHON_KEYWORDS = new Set([
  "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue",
  "def", "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import", "in",
  "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while", "with", "yield",
]);

const PYTHON_IDENTIFIER = /^[\p{XID_Start}_][\p{XID_Continue}]*$/u;

function pythonIdentifier(name: string, contractName: string): string {
  if (!PYTHON_IDENTIFIER.test(name)) {
    throw new Error(
      `Cannot generate Python: ${JSON.stringify(contractName)} is not a Python identifier (as ${JSON.stringify(name)})`,
    );
  }
  return PYTHON_KEYWORDS.has(name) ? `${name}_` : name;
}

/** The snake_case Python name of a contract id or argument name. */
export function pythonSnake(name: string): string {
  return pythonIdentifier(toCamelCase(name).replace(/\p{Lu}/gu, (c) => `_${c.toLowerCase()}`), name);
}

/** The Python type name of a contract id. */
export function pythonType(name: string): string {
  return pythonIdentifier(toPascalCase(name), name);
}

/** A Python string literal. JSON's escapes are Python's. */
export function pythonString(s: string): string {
  return JSON.stringify(s);
}

/** A JSON value as a Python literal of the runtime's values. */
export function pythonValue(v: unknown): string {
  if (v === null || v === undefined) return "None";
  if (typeof v === "boolean") return v ? "True" : "False";
  if (typeof v === "number") {
    const text = JSON.stringify(v);
    return text === "null" ? "None" : `rt.Number(${pythonString(text)})`;
  }
  if (typeof v === "string") return pythonString(v);
  if (Array.isArray(v)) return `[${v.map(pythonValue).join(", ")}]`;
  const entries = Object.entries(v as Record<string, unknown>).filter(([, value]) => value !== undefined);
  return `{${entries.map(([k, value]) => `${pythonString(k)}: ${pythonValue(value)}`).join(", ")}}`;
}

function pythonStrings(items: string[]): string {
  return `[${items.map(pythonString).join(", ")}]`;
}

const HEADER = "# Code generated by cli-contracts. DO NOT EDIT.\n";

function handlerOptionsType(cmd: SpecCommand): string {
  return `${pythonType(cmd.id)}HandlerOptions`;
}

function handlerOptionType(type: SpecCommand["options"][number]["type"]): string {
  return type === "boolean" ? "bool" : type === "strings" ? "List[str]" : "str";
}

export function pythonHandlerSignature(cmd: SpecCommand, optionsPrefix = ""): string {
  const params = ["self"];
  for (const arg of cmd.arguments) {
    const type = arg.variadic ? "List[str]" : arg.required ? "str" : "Optional[str]";
    params.push(`${pythonSnake(arg.name)}: ${type}`);
  }
  params.push(`options: ${optionsPrefix}${handlerOptionsType(cmd)}`, "parent_opts: Dict[str, Any]");
  const returns = cmd.llm ? "Union[int, str, Tuple[int, Optional[str]], None]" : "Optional[int]";
  return `def ${pythonSnake(cmd.id)}(${params.join(", ")}) -> ${returns}`;
}

function renderOption(opt: TreeOption): string {
  const fields = [`flags=${pythonString(opt.flags)}`, `name=${pythonString(opt.name)}`, `key=${pythonString(opt.key)}`];
  fields.push(`kind=rt.${opt.kind === "flag" ? "FLAG" : opt.kind === "negate" ? "NEGATE" : "TAKES_VALUE"}`);
  if (opt.short !== undefined) fields.push(`short=${pythonString(opt.short)}`);
  if (opt.long !== undefined) fields.push(`long=${pythonString(opt.long)}`);
  if (opt.variadic) fields.push("variadic=True");
  if (opt.version) fields.push("version=True");
  return `rt.Option(${fields.join(", ")})`;
}

function renderNode(node: TreeNode, indent: string): string {
  const i1 = indent + "    ";
  const fields = [`name=${pythonString(node.name)}`, `help=${pythonString(node.help)}`];
  if (node.options.length > 0) {
    fields.push(`options=[\n${node.options.map((o) => `${i1}    ${renderOption(o)},`).join("\n")}\n${i1}]`);
  }
  if (node.initialValues.length > 0) {
    fields.push(`initial_values=[${node.initialValues.map(([k, v]) => `(${pythonString(k)}, ${pythonValue(v)})`).join(", ")}]`);
  }
  if (node.arguments.length > 0) {
    fields.push(
      `arguments=[${node.arguments
        .map((a) => `rt.Argument(name=${pythonString(a.name)}, required=${a.required ? "True" : "False"}, variadic=${a.variadic ? "True" : "False"})`)
        .join(", ")}]`,
    );
  }
  if (node.commands.length > 0) {
    fields.push(`commands=[\n${node.commands.map((c) => `${i1}    ${renderNode(c, i1 + "    ")},`).join("\n")}\n${i1}]`);
  }
  if (node.hidden) fields.push("hidden=True");
  if (node.defaultCommand !== undefined) fields.push(`default_command=${pythonString(node.defaultCommand)}`);
  if (node.helpCommand !== undefined) fields.push(`help_command=${pythonString(node.helpCommand)}`);
  if (node.helpShort !== undefined) fields.push(`help_short=${pythonString(node.helpShort)}`);
  if (node.helpLong !== undefined) fields.push(`help_long=${pythonString(node.helpLong)}`);
  if (node.action?.kind === "extract") {
    fields.push("action=rt.Action(extract=True)");
  } else if (node.action) {
    fields.push(
      `action=rt.Action(command_id=${pythonString(node.action.commandId)}, llm=${node.action.llm ? "True" : "False"}, introspect=${node.action.introspect ? "True" : "False"})`,
    );
  }
  if (node.optionSuggestions.length > 0) fields.push(`option_suggestions=${pythonStrings(node.optionSuggestions)}`);
  if (node.commandSuggestions.length > 0) fields.push(`command_suggestions=${pythonStrings(node.commandSuggestions)}`);
  if (node.digitShortOption) fields.push("digit_short_option=True");
  return `rt.Command(\n${fields.map((f) => `${i1}${f},`).join("\n")}\n${indent})`;
}

/** The contract's commands, one per id (a later command of the same id replaces an earlier one, as in TypeScript). */
function uniqueCommands(spec: RuntimeSpec): SpecCommand[] {
  return [...new Map(spec.commands.map((cmd) => [cmd.id, cmd])).values()];
}

function dispatchCall(cmd: SpecCommand): string {
  const args = cmd.arguments.map((_, i) => `inv.args[${i}]`);
  args.push("dict(inv.opts)", "inv.globals");
  return `handlers.${pythonSnake(cmd.id)}(${args.join(", ")})`;
}

function generateProgram(spec: RuntimeSpec): string {
  const commands = uniqueCommands(spec);
  const lines: string[] = [
    HEADER,
    "from __future__ import annotations",
    "",
    "from typing import Any, Callable, Dict, List, Optional, Tuple, Union",
    "",
    "from typing import Protocol, TypedDict",
    "",
    "import cli_contracts_runtime as rt",
    "",
  ];
  if (spec.policyDefinitions) lines.push("from .policy import COMMAND_DEFINITIONS", "");

  for (const cmd of commands) {
    lines.push(`# The options the program passes to the ${cmd.id} handler, as given, keyed as the program keys them.`);
    const fields = cmd.options.map((opt) => `${pythonString(opt.key)}: ${handlerOptionType(opt.type)}`);
    lines.push(`${handlerOptionsType(cmd)} = TypedDict(${pythonString(handlerOptionsType(cmd))}, {${fields.join(", ")}}, total=False)`, "");
  }
  lines.push("");

  lines.push("class CommandHandlers(Protocol):");
  lines.push('    """Runs the contract\'s commands. A handler returns the exit code (None for 0);');
  lines.push("    a command that takes --adapter may return the prompt it built instead, or");
  lines.push('    both as (exit code, prompt); the program writes the prompt with --show-prompt."""');
  for (const cmd of commands) {
    lines.push("", `    ${pythonHandlerSignature(cmd)}:`, "        ...");
  }
  lines.push("", "");

  lines.push("def create_program(");
  lines.push("    handlers: CommandHandlers,");
  lines.push("    version: str,");
  lines.push("    on_usage_error: Optional[Callable[[rt.UsageError, rt.Command], int]] = None,");
  lines.push(") -> rt.Program:");
  lines.push('    """Creates the program. ``version`` is what --version writes. ``on_usage_error``');
  lines.push("    ends an invocation the program rejects: it writes what the contract declares");
  lines.push("    for invalid arguments and returns the exit code; without it, the program");
  lines.push('    writes the error\'s message and exits 1."""');
  lines.push("");
  lines.push("    def dispatch(command_id: str, inv: rt.Invocation) -> rt.Outcome:");
  commands.forEach((cmd, i) => {
    lines.push(`        ${i === 0 ? "if" : "elif"} command_id == ${pythonString(cmd.id)}:`);
    lines.push(`            return rt.outcome(${dispatchCall(cmd)})`);
  });
  lines.push('        raise KeyError(command_id)');
  lines.push("");
  lines.push("    return rt.Program(");
  lines.push("        _tree(),");
  lines.push("        version,");
  lines.push("        dispatch,");
  lines.push("        on_usage_error,");
  lines.push(`        ${spec.policyDefinitions ? "COMMAND_DEFINITIONS" : "None"},`);
  lines.push(`        ${spec.extract ? "_extract_spec()" : "None"},`);
  lines.push("    )", "", "");

  lines.push("def _tree() -> rt.Command:");
  lines.push(`    return ${renderNode(spec.tree, "    ")}`);
  lines.push("");

  if (spec.extract) {
    const x = spec.extract;
    lines.push("", "def _extract_spec() -> rt.ExtractSpec:");
    lines.push("    return rt.ExtractSpec(");
    lines.push(`        yaml_with_meta=${pythonString(x.yamlWithMeta)},`);
    lines.push(`        yaml_without_meta=${pythonString(x.yamlWithoutMeta)},`);
    lines.push(`        json_with_meta=${pythonString(x.jsonWithMeta)},`);
    lines.push(`        json_without_meta=${pythonString(x.jsonWithoutMeta)},`);
    lines.push(`        filter_head=${pythonString(x.filter.head)},`);
    lines.push(`        filter_tail=${pythonString(x.filter.tail)},`);
    lines.push("        sets=[");
    for (const set of x.filter.sets) {
      lines.push(
        `            rt.ExtractSet(id=${pythonString(set.id)}, key=${pythonString(set.key)}, before=${pythonStrings(set.before)}, after=${pythonStrings(set.after)}, commands=[${set.commands.map((c) => `(${pythonString(c.id)}, ${pythonString(c.text)})`).join(", ")}]),`,
      );
    }
    lines.push("        ],", "    )", "");
  }
  return lines.filter((line, i, all) => !(line === "" && all[i - 1] === "" && all[i - 2] === "")).join("\n");
}

function generatePolicy(spec: RuntimeSpec): string {
  const lines = [HEADER, "from __future__ import annotations", "", "from typing import Any, Dict", "", "import cli_contracts_runtime as rt", ""];
  lines.push("# By command id, the part of each command's contract its policy is derived from.");
  lines.push("COMMAND_DEFINITIONS: Dict[str, Any] = {");
  for (const [id, def] of spec.policyDefinitions!) lines.push(`    ${pythonString(id)}: ${pythonValue(def)},`);
  lines.push("}", "", "");
  lines.push("def derive_command_policy(command_id: str, option_values: Dict[str, Any]) -> Dict[str, Any]:");
  lines.push('    """Derives a command\'s policy from its option values, keyed as the program');
  lines.push('    keys them (dry-run -> dryRun)."""');
  lines.push("    if command_id not in COMMAND_DEFINITIONS:");
  lines.push('        raise ValueError(f"Unknown command: {command_id}")');
  lines.push("    return rt.introspect(command_id, COMMAND_DEFINITIONS[command_id], option_values)");
  lines.push("");
  return lines.join("\n");
}

function generateContract(spec: RuntimeSpec): string {
  return [
    HEADER,
    "# The contract the program was generated from.",
    `CONTRACT_YAML = ${pythonString(spec.contract!.yaml)}`,
    "",
    "# The contract as JSON.",
    `CONTRACT_JSON = ${pythonString(spec.contract!.json)}`,
    "",
  ].join("\n");
}

export function generatePython(ctx: NormalizedContext, options: PythonGeneratorOptions = {}): Record<string, string> {
  const spec = buildRuntimeSpec(ctx, options.contractYaml);
  const model = buildTypeModel(ctx);
  const output: Record<string, string> = {
    "program.py": generateProgram(spec),
    "types.py": generatePythonTypes(model),
    "commands.py": generatePythonCommands(model),
    "schemas.py": generatePythonSchemas(model),
  };
  const exports = [
    "from .program import CommandHandlers, create_program",
    "from .types import *  # noqa: F401,F403",
    "from .commands import *  # noqa: F401,F403",
    "from .schemas import *  # noqa: F401,F403",
  ];
  if (spec.policyDefinitions) {
    output["policy.py"] = generatePolicy(spec);
    exports.push("from .policy import COMMAND_DEFINITIONS, derive_command_policy");
  }
  if (spec.contract) {
    output["contract.py"] = generateContract(spec);
    exports.push("from .contract import CONTRACT_JSON, CONTRACT_YAML");
  }
  output["__init__.py"] = [HEADER, ...exports, ""].join("\n");
  return output;
}

