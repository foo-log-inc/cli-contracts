import type { NormalizedContext } from "../types.js";
import { buildRuntimeSpec, type RuntimeSpec, type SpecCommand } from "./runtime-spec.js";
import type { TreeNode, TreeOption } from "./commander-tree.js";
import { toCamelCase, toPascalCase } from "./typescript.js";
import { buildTypeModel, type Decl, type Field, type TypeExpr, type TypeModel } from "./type-model.js";

// The PHP program of a contract: the command tree, handler interface and
// dispatch for the runtime package cli-contracts/runtime (namespace
// CliContracts\Runtime), which parses an invocation by commander's rules.
// Everything here is rendered from the runtime spec (runtime-spec.ts);
// nothing is decided here. One class per file, for PSR-4.

export interface PhpGeneratorOptions {
  /** The namespace of the generated classes, e.g. `App\Cli`. */
  namespace: string;
  contractYaml?: string;
}

const PHP_IDENTIFIER = /^[A-Za-z_\x80-\uffff][A-Za-z0-9_\x80-\uffff]*$/u;

function phpIdentifier(name: string, contractName: string): string {
  if (!PHP_IDENTIFIER.test(name)) {
    throw new Error(
      `Cannot generate PHP: ${JSON.stringify(contractName)} is not a PHP identifier (as ${JSON.stringify(name)})`,
    );
  }
  return name;
}

/** The PHP method name of a contract id. */
export function phpMethod(id: string): string {
  return phpIdentifier(toCamelCase(id), id);
}

/** The PHP variable name (without `$`) of an argument. */
export function phpVariable(name: string): string {
  const camel = toCamelCase(name);
  return phpIdentifier(camel === "this" ? "thisArg" : camel, name);
}

/** A PHP double-quoted string literal. */
export function phpString(s: string): string {
  let out = '"';
  for (const ch of s) {
    const code = ch.codePointAt(0)!;
    if (ch === '"') out += '\\"';
    else if (ch === "\\") out += "\\\\";
    else if (ch === "$") out += "\\$";
    else if (ch === "\n") out += "\\n";
    else if (ch === "\r") out += "\\r";
    else if (ch === "\t") out += "\\t";
    else if (code < 0x20 || code === 0x7f) out += `\\u{${code.toString(16)}}`;
    else out += ch;
  }
  return out + '"';
}

/** A JSON value as a PHP expression of the runtime's values. */
export function phpValue(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return String(v);
  if (typeof v === "number") {
    const text = JSON.stringify(v);
    return text === "null" ? "null" : `new Rt\\JsonNumber(${phpString(text)})`;
  }
  if (typeof v === "string") return phpString(v);
  if (Array.isArray(v)) return `[${v.map(phpValue).join(", ")}]`;
  const entries = Object.entries(v as Record<string, unknown>).filter(([, value]) => value !== undefined);
  return `new Rt\\JsonObject([${entries.map(([k, value]) => `${phpString(k)} => ${phpValue(value)}`).join(", ")}])`;
}

function phpStrings(items: string[]): string {
  return `[${items.map(phpString).join(", ")}]`;
}

function fileHeader(namespace: string): string[] {
  return ["<?php", "", "// Code generated by cli-contracts. DO NOT EDIT.", "", "declare(strict_types=1);", "", `namespace ${namespace};`, ""];
}

function handlerOptionShape(cmd: SpecCommand): string {
  const fields = cmd.options.map((opt) => {
    const type = opt.type === "boolean" ? "bool" : opt.type === "strings" ? "list<string>" : "string";
    return `${/^[A-Za-z_][A-Za-z0-9_]*$/.test(opt.key) ? opt.key : `'${opt.key}'`}?: ${type}`;
  });
  return `array{${fields.join(", ")}}`;
}

export function phpHandlerSignature(cmd: SpecCommand): string {
  const params = cmd.arguments.map((arg) => {
    const type = arg.variadic ? "array" : arg.required ? "string" : "?string";
    return `${type} $${phpVariable(arg.name)}`;
  });
  params.push("array $options", "array $parentOpts");
  return `public function ${phpMethod(cmd.id)}(${params.join(", ")}): ${cmd.llm ? "int|string|array|null" : "?int"}`;
}

function renderOption(opt: TreeOption): string {
  const fields = [`flags: ${phpString(opt.flags)}`, `name: ${phpString(opt.name)}`, `key: ${phpString(opt.key)}`];
  fields.push(`kind: Rt\\Option::${opt.kind === "flag" ? "FLAG" : opt.kind === "negate" ? "NEGATE" : "TAKES_VALUE"}`);
  if (opt.short !== undefined) fields.push(`short: ${phpString(opt.short)}`);
  if (opt.long !== undefined) fields.push(`long: ${phpString(opt.long)}`);
  if (opt.variadic) fields.push("variadic: true");
  if (opt.version) fields.push("version: true");
  return `new Rt\\Option(${fields.join(", ")})`;
}

function renderNode(node: TreeNode, indent: string): string {
  const i1 = indent + "    ";
  const fields = [`name: ${phpString(node.name)}`, `help: ${phpString(node.help)}`];
  if (node.options.length > 0) {
    fields.push(`options: [\n${node.options.map((o) => `${i1}    ${renderOption(o)},`).join("\n")}\n${i1}]`);
  }
  if (node.initialValues.length > 0) {
    fields.push(`initialValues: [${node.initialValues.map(([k, v]) => `${phpString(k)} => ${phpValue(v)}`).join(", ")}]`);
  }
  if (node.arguments.length > 0) {
    fields.push(
      `arguments: [${node.arguments
        .map((a) => `new Rt\\Argument(${phpString(a.name)}, ${a.required}, ${a.variadic})`)
        .join(", ")}]`,
    );
  }
  if (node.commands.length > 0) {
    fields.push(`commands: [\n${node.commands.map((c) => `${i1}    ${renderNode(c, i1 + "    ")},`).join("\n")}\n${i1}]`);
  }
  if (node.hidden) fields.push("hidden: true");
  if (node.defaultCommand !== undefined) fields.push(`defaultCommand: ${phpString(node.defaultCommand)}`);
  if (node.helpCommand !== undefined) fields.push(`helpCommand: ${phpString(node.helpCommand)}`);
  if (node.helpShort !== undefined) fields.push(`helpShort: ${phpString(node.helpShort)}`);
  if (node.helpLong !== undefined) fields.push(`helpLong: ${phpString(node.helpLong)}`);
  if (node.action?.kind === "extract") {
    fields.push("action: new Rt\\Action(extract: true)");
  } else if (node.action) {
    fields.push(
      `action: new Rt\\Action(commandId: ${phpString(node.action.commandId)}, llm: ${node.action.llm}, introspect: ${node.action.introspect})`,
    );
  }
  if (node.optionSuggestions.length > 0) fields.push(`optionSuggestions: ${phpStrings(node.optionSuggestions)}`);
  if (node.commandSuggestions.length > 0) fields.push(`commandSuggestions: ${phpStrings(node.commandSuggestions)}`);
  if (node.digitShortOption) fields.push("digitShortOption: true");
  return `new Rt\\Command(\n${fields.map((f) => `${i1}${f},`).join("\n")}\n${indent})`;
}

/** The contract's commands, one per id (a later command of the same id replaces an earlier one, as in TypeScript). */
function uniqueCommands(spec: RuntimeSpec): SpecCommand[] {
  return [...new Map(spec.commands.map((cmd) => [cmd.id, cmd])).values()];
}

function generateHandlers(spec: RuntimeSpec, namespace: string): string {
  const lines = fileHeader(namespace);
  lines.push("/**");
  lines.push(" * Runs the contract's commands. A handler returns the exit code (null for 0);");
  lines.push(" * a command that takes --adapter may return the prompt it built instead, or");
  lines.push(" * both as [exit code, prompt]; the program writes the prompt with --show-prompt.");
  lines.push(" */");
  lines.push("interface CommandHandlers");
  lines.push("{");
  uniqueCommands(spec).forEach((cmd, i) => {
    if (i > 0) lines.push("");
    lines.push("    /**");
    lines.push(`     * ${cmd.id}`);
    lines.push("     *");
    for (const arg of cmd.arguments) {
      lines.push(`     * @param ${arg.variadic ? "list<string>" : arg.required ? "string" : "?string"} $${phpVariable(arg.name)}`);
    }
    lines.push(`     * @param ${handlerOptionShape(cmd)} $options the options as given, keyed as the program keys them`);
    lines.push("     * @param array<string, mixed> $parentOpts");
    lines.push("     */");
    lines.push(`    ${phpHandlerSignature(cmd)};`);
  });
  lines.push("}", "");
  return lines.join("\n");
}

function generateProgram(spec: RuntimeSpec, namespace: string): string {
  const lines = fileHeader(namespace);
  lines.push("use CliContracts\\Runtime as Rt;", "");
  lines.push("final class Program");
  lines.push("{");
  lines.push("    /**");
  lines.push("     * Creates the program. $version is what --version writes. $onUsageError ends an");
  lines.push("     * invocation the program rejects: it writes what the contract declares for");
  lines.push("     * invalid arguments and returns the exit code; without it, the program writes");
  lines.push("     * the error's message and exits 1.");
  lines.push("     *");
  lines.push("     * @param (\\Closure(Rt\\UsageError, Rt\\Command): int)|null $onUsageError");
  lines.push("     */");
  lines.push("    public static function create(CommandHandlers $handlers, string $version, ?\\Closure $onUsageError = null): Rt\\Program");
  lines.push("    {");
  lines.push("        $dispatch = static function (string $commandId, Rt\\Invocation $inv) use ($handlers): Rt\\Outcome {");
  lines.push("            return Rt\\Outcome::of(match ($commandId) {");
  for (const cmd of uniqueCommands(spec)) {
    const args = cmd.arguments.map((_, i) => `$inv->args[${i}]`);
    args.push("$inv->opts", "$inv->globals");
    lines.push(`                ${phpString(cmd.id)} => $handlers->${phpMethod(cmd.id)}(${args.join(", ")}),`);
  }
  lines.push("                default => throw new \\LogicException(\"Unknown command: {$commandId}\"),");
  lines.push("            });");
  lines.push("        };");
  lines.push("        return new Rt\\Program(");
  lines.push("            self::tree(),");
  lines.push("            $version,");
  lines.push("            $dispatch,");
  lines.push("            $onUsageError,");
  lines.push(`            ${spec.policyDefinitions ? "Policy::commandDefinitions()" : "[]"},`);
  lines.push(`            ${spec.extract ? "self::extractSpec()" : "null"},`);
  lines.push("        );");
  lines.push("    }", "");
  lines.push("    private static function tree(): Rt\\Command");
  lines.push("    {");
  lines.push(`        return ${renderNode(spec.tree, "        ")};`);
  lines.push("    }");
  if (spec.extract) {
    const x = spec.extract;
    lines.push("", "    private static function extractSpec(): Rt\\ExtractSpec");
    lines.push("    {");
    lines.push("        return new Rt\\ExtractSpec(");
    lines.push(`            yamlWithMeta: ${phpString(x.yamlWithMeta)},`);
    lines.push(`            yamlWithoutMeta: ${phpString(x.yamlWithoutMeta)},`);
    lines.push(`            jsonWithMeta: ${phpString(x.jsonWithMeta)},`);
    lines.push(`            jsonWithoutMeta: ${phpString(x.jsonWithoutMeta)},`);
    lines.push(`            filterHead: ${phpString(x.filter.head)},`);
    lines.push(`            filterTail: ${phpString(x.filter.tail)},`);
    lines.push("            sets: [");
    for (const set of x.filter.sets) {
      lines.push(
        `                new Rt\\ExtractSet(${phpString(set.id)}, ${phpString(set.key)}, ${phpStrings(set.before)}, ${phpStrings(set.after)}, [${set.commands.map((c) => `[${phpString(c.id)}, ${phpString(c.text)}]`).join(", ")}]),`,
      );
    }
    lines.push("            ],", "        );", "    }");
  }
  lines.push("}", "");
  return lines.join("\n");
}

function generatePolicy(spec: RuntimeSpec, namespace: string): string {
  const lines = fileHeader(namespace);
  lines.push("use CliContracts\\Runtime as Rt;", "");
  lines.push("final class Policy");
  lines.push("{");
  lines.push("    /**");
  lines.push("     * By command id, the part of each command's contract its policy is derived from.");
  lines.push("     *");
  lines.push("     * @return array<string, mixed>");
  lines.push("     */");
  lines.push("    public static function commandDefinitions(): array");
  lines.push("    {");
  lines.push("        $definitions = [];");
  for (const [id, def] of spec.policyDefinitions!) lines.push(`        $definitions[${phpString(id)}] = ${phpValue(def)};`);
  lines.push("        return $definitions;");
  lines.push("    }", "");
  lines.push("    /**");
  lines.push("     * Derives a command's policy from its option values, keyed as the program");
  lines.push("     * keys them (dry-run -> dryRun).");
  lines.push("     *");
  lines.push("     * @param array<string, mixed> $optionValues");
  lines.push("     */");
  lines.push("    public static function deriveCommandPolicy(string $commandId, array $optionValues): Rt\\JsonObject");
  lines.push("    {");
  lines.push("        $definitions = self::commandDefinitions();");
  lines.push("        if (!array_key_exists($commandId, $definitions)) {");
  lines.push("            throw new \\InvalidArgumentException(\"Unknown command: {$commandId}\");");
  lines.push("        }");
  lines.push("        return Rt\\Policy::introspect($commandId, $definitions[$commandId], $optionValues);");
  lines.push("    }");
  lines.push("}", "");
  return lines.join("\n");
}

function generateContract(spec: RuntimeSpec, namespace: string): string {
  const lines = fileHeader(namespace);
  lines.push("final class Contract");
  lines.push("{");
  lines.push("    /** The contract the program was generated from. */");
  lines.push(`    public const YAML = ${phpString(spec.contract!.yaml)};`, "");
  lines.push("    /** The contract as JSON. */");
  lines.push(`    public const JSON = ${phpString(spec.contract!.json)};`);
  lines.push("}", "");
  return lines.join("\n");
}

const PHP_NAMESPACE = /^[A-Za-z_][A-Za-z0-9_]*(\\[A-Za-z_][A-Za-z0-9_]*)*$/;

export function generatePhp(ctx: NormalizedContext, options: PhpGeneratorOptions): Record<string, string> {
  if (!PHP_NAMESPACE.test(options.namespace)) {
    throw new Error(`Cannot generate PHP: ${JSON.stringify(options.namespace)} is not a namespace`);
  }
  const spec = buildRuntimeSpec(ctx, options.contractYaml);
  const output: Record<string, string> = {
    "CommandHandlers.php": generateHandlers(spec, options.namespace),
    "Program.php": generateProgram(spec, options.namespace),
  };
  const model = buildTypeModel(ctx);
  const decls: Decls = new Map(model.decls.map((d) => [d.name, d]));
  output["Types.php"] = generatePhpTypes(model, options.namespace);
  output["Commands.php"] = generatePhpCommands(model, options.namespace);
  output["Schemas.php"] = generatePhpSchemas(model, options.namespace);
  for (const cmd of model.commands) {
    const prefix = phpIdentifier(toPascalCase(cmd.id), cmd.id);
    if (cmd.arguments.length > 0) {
      output[`${prefix}Args.php`] = phpValueClass(`${prefix}Args`, `The arguments of ${cmd.id}.`, cmd.arguments.map((a) => ({ ...a, optional: a.optional })), options.namespace, decls);
    }
    if (cmd.options.length > 0) {
      output[`${prefix}Options.php`] = phpValueClass(`${prefix}Options`, `The options of ${cmd.id}; null is not given.`, cmd.options.map((o) => ({ ...o, optional: true })), options.namespace, decls);
    }
  }
  if (spec.policyDefinitions) output["Policy.php"] = generatePolicy(spec, options.namespace);
  if (spec.contract) output["Contract.php"] = generateContract(spec, options.namespace);
  return output;
}

// ─── Types.php, <Cmd>Args.php, <Cmd>Options.php, Commands.php, Schemas.php ──

type Decls = Map<string, Decl>;

/** The PHPStan type of a type expression. */
function phpDocType(type: TypeExpr): string {
  switch (type.kind) {
    case "string":
      return "string";
    case "integer":
      return "int";
    case "number":
      return "float";
    case "boolean":
      return "bool";
    case "ref":
      return phpIdentifier(type.name, type.name);
    case "literals":
      return type.values.length === 0 ? "mixed" : type.values.map(phpDocLiteral).join("|");
    case "union":
      return type.members.length === 0 ? "mixed" : type.members.map(phpDocType).join("|");
    case "array":
      return `list<${phpDocType(type.items)}>`;
    case "map":
      return "array<string, mixed>";
    default:
      return "mixed";
  }
}

function phpDocLiteral(v: unknown): string {
  if (v === null) return "null";
  if (typeof v === "string") return `'${v.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
  return String(v);
}

function phpDocKey(name: string): string {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : phpDocLiteral(name);
}

function phpDocShape(fields: Field[]): string {
  return `array{${fields.map((f) => `${phpDocKey(f.name)}${f.optional ? "?" : ""}: ${phpDocType(f.type)}`).join(", ")}}`;
}

/** The PHP property type of a type expression. */
function phpPropertyType(type: TypeExpr, decls: Decls): string {
  switch (type.kind) {
    case "string":
      return "string";
    case "integer":
      return "int";
    case "number":
      return "float";
    case "boolean":
      return "bool";
    case "literals":
      return type.values.every((v) => typeof v === "string") ? "string" : "mixed";
    case "array":
    case "map":
      return "array";
    case "ref": {
      const decl = decls.get(type.name);
      if (decl?.kind === "enum") return "string";
      if (decl?.kind === "record") return "array";
      return decl?.kind === "alias" ? phpPropertyType(decl.type, decls) : "mixed";
    }
    default:
      return "mixed";
  }
}

function generatePhpTypes(model: TypeModel, namespace: string): string {
  const lines = fileHeader(namespace);
  lines.push("/**", " * The contract's types, as PHPStan type aliases (import them with @phpstan-import-type).", " *");
  for (const decl of model.decls) {
    const name = phpIdentifier(decl.name, decl.name);
    const type =
      decl.kind === "record"
        ? phpDocShape(decl.fields)
        : decl.kind === "enum"
          ? decl.values.map(phpDocLiteral).join("|")
          : phpDocType(decl.type);
    lines.push(` * @phpstan-type ${name} ${type}`);
  }
  for (const cmd of model.commands) {
    const prefix = phpIdentifier(toPascalCase(cmd.id), cmd.id);
    lines.push(` * @phpstan-type ${prefix}ExitCode ${cmd.exitCodes.join("|")}`);
    const variants = cmd.exits.map((exit) => {
      const fields: Field[] = [{ name: "exitCode", optional: false, type: { kind: "literals", values: [exit.code] } }];
      if (exit.stdout) fields.push({ name: "stdout", optional: exit.stdout.optional, type: exit.stdout.type });
      if (exit.stderr) fields.push({ name: "stderr", optional: exit.stderr.optional, type: exit.stderr.type });
      return phpDocShape(fields);
    });
    lines.push(` * @phpstan-type ${prefix}ExitResult ${variants.join("|")}`);
  }
  lines.push(" */", "final class Types", "{", "}", "");
  return lines.join("\n");
}

/** A class of named, typed, read-only values: a command's arguments or options. */
function phpValueClass(name: string, description: string, fields: Array<{ name: string; type: TypeExpr; optional: boolean; variadic?: boolean }>, namespace: string, decls: Decls): string {
  const lines = fileHeader(namespace);
  // A parameter with a default follows those without one.
  const ordered = [...fields.filter((f) => !f.optional), ...fields.filter((f) => f.optional)];
  lines.push("/**", ` * ${description}`, " *");
  for (const f of ordered) lines.push(` * @param ${phpDocType(f.type)}${f.optional ? "|null" : ""} $${phpVariable(f.name)}`);
  lines.push(" */", `final class ${name}`, "{", "    public function __construct(");
  for (const f of ordered) {
    const t = phpPropertyType(f.type, decls);
    const declared = f.optional ? (t === "mixed" ? "mixed" : `?${t}`) : t;
    lines.push(`        public readonly ${declared} $${phpVariable(f.name)}${f.optional ? " = null" : ""},`);
  }
  lines.push("    ) {", "    }", "}", "");
  return lines.join("\n");
}

/** How a value of a type is written as an argument. */
function phpArgString(type: TypeExpr, expr: string, decls: Decls): string {
  const t = phpPropertyType(type, decls);
  if (t === "string") return expr;
  if (t === "int") return `(string) ${expr}`;
  if (t === "float") return `Rt\\Client::formatNumber(${expr})`;
  if (t === "bool") return `(${expr} ? 'true' : 'false')`;
  return `Rt\\Client::argString(${expr})`;
}

function generatePhpCommands(model: TypeModel, namespace: string): string {
  const decls: Decls = new Map(model.decls.map((d) => [d.name, d]));
  const lines = fileHeader(namespace);
  lines.push("use CliContracts\\Runtime as Rt;", "", "final class Commands", "{");
  model.commands.forEach((cmd, i) => {
    const prefix = phpIdentifier(toPascalCase(cmd.id), cmd.id);
    const params = ["string $executable"];
    if (cmd.arguments.length > 0) params.push(`${prefix}Args $args`);
    if (cmd.options.length > 0) params.push(`?${prefix}Options $options = null`);
    if (i > 0) lines.push("");
    lines.push(`    /** Runs ${cmd.id} with the arguments and options given. */`);
    lines.push(`    public static function ${phpMethod(cmd.fullId)}(${params.join(", ")}): Rt\\ExecResult`, "    {");
    lines.push(`        $cmdArgs = ${phpStrings(cmd.path)};`);
    for (const arg of cmd.arguments) {
      const field = `$args->${phpVariable(arg.name)}`;
      if (arg.variadic) lines.push(`        array_push($cmdArgs, ...(${field} ?? []));`);
      else if (arg.optional) lines.push(`        if (${field} !== null) {`, `            $cmdArgs[] = ${phpArgString(arg.type, field, decls)};`, "        }");
      else lines.push(`        $cmdArgs[] = ${phpArgString(arg.type, field, decls)};`);
    }
    if (cmd.options.length > 0) {
      lines.push("        if ($options !== null) {");
      for (const opt of cmd.options) {
        const field = `$options->${phpVariable(opt.name)}`;
        if (opt.negated !== undefined) {
          lines.push(`            if (${field} !== null) {`, `                $cmdArgs[] = ${field} ? ${phpString(opt.long)} : ${phpString(opt.negated)};`, "            }");
        } else if (opt.boolean) {
          lines.push(`            if (${field} === true) {`, `                $cmdArgs[] = ${phpString(opt.long)};`, "            }");
        } else if (opt.repeatable && opt.type.kind === "array") {
          lines.push(`            foreach (${field} ?? [] as $v) {`, `                $cmdArgs[] = ${phpString(opt.long)};`, `                $cmdArgs[] = ${phpArgString(opt.type.items, "$v", decls)};`, "            }");
        } else {
          lines.push(`            if (${field} !== null) {`, `                $cmdArgs[] = ${phpString(opt.long)};`, `                $cmdArgs[] = ${phpArgString(opt.type, field, decls)};`, "            }");
        }
      }
      lines.push("        }");
    }
    lines.push("        return Rt\\Client::exec($executable, $cmdArgs);", "    }");
  });
  lines.push("}", "");
  return lines.join("\n");
}

function generatePhpSchemas(model: TypeModel, namespace: string): string {
  const lines = fileHeader(namespace);
  lines.push("final class Schemas", "{");
  lines.push("    /** The components' JSON Schemas as JSON, by name. */");
  lines.push(`    public const SCHEMAS = [${model.schemas.map(([n, s]) => `${phpString(n)} => ${phpString(JSON.stringify(s))}`).join(", ")}];`);
  for (const cmd of model.commands) {
    lines.push("", `    /** The exit codes ${cmd.id} declares. */`);
    lines.push(`    public const ${toCamelCase(cmd.id).replace(/\p{Lu}/gu, (c) => `_${c}`).toUpperCase()}_EXIT_CODES = [${cmd.exitCodes.join(", ")}];`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

/** A JSON value as a PHP literal of a type. */
export function phpLiteral(value: unknown, type: TypeExpr, model: TypeModel): string {
  const decls: Decls = new Map(model.decls.map((d) => [d.name, d]));
  if (Array.isArray(value)) return `[${value.map((v) => phpLiteral(v, type.kind === "array" ? type.items : { kind: "unknown" }, model)).join(", ")}]`;
  if (typeof value === "string") return phpString(value);
  if (typeof value === "boolean") return String(value);
  if (typeof value === "number") {
    return phpPropertyType(type, decls) === "float" && Number.isInteger(value) ? `${value}.0` : String(value);
  }
  throw new Error(`No PHP literal for ${JSON.stringify(value)}`);
}
