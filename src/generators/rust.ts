import type { NormalizedContext } from "../types.js";
import { buildRuntimeSpec, type RuntimeSpec, type SpecCommand } from "./runtime-spec.js";
import type { TreeNode, TreeOption } from "./commander-tree.js";
import { toCamelCase, toPascalCase } from "./typescript.js";

// The Rust program of a contract: the command tree, handler trait and
// dispatch for the runtime crate cli_contracts_runtime, which parses an
// invocation by commander's rules. Everything here is rendered from the
// runtime spec (runtime-spec.ts); nothing is decided here. Items whose layout
// depends on the contract's data carry #[rustfmt::skip].

export interface RustGeneratorOptions {
  contractYaml?: string;
}

const RUST_KEYWORDS = new Set([
  "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
  "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
  "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
  "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
  "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
]);
/** Keywords a raw identifier cannot spell. */
const NOT_RAW = new Set(["crate", "self", "Self", "super"]);

const RUST_IDENTIFIER = /^[\p{XID_Start}_][\p{XID_Continue}]*$/u;

function rustIdentifier(name: string, contractName: string): string {
  if (!RUST_IDENTIFIER.test(name) || name === "_") {
    throw new Error(
      `Cannot generate Rust: ${JSON.stringify(contractName)} is not a Rust identifier (as ${JSON.stringify(name)})`,
    );
  }
  if (NOT_RAW.has(name)) return `${name}_`;
  return RUST_KEYWORDS.has(name) ? `r#${name}` : name;
}

/** The snake_case Rust name of a contract id, key or argument name. */
export function rustSnake(name: string): string {
  const camel = toCamelCase(name);
  return rustIdentifier(camel.replace(/\p{Lu}/gu, (c) => `_${c.toLowerCase()}`), name);
}

/** The Rust type name of a contract id. */
export function rustType(name: string): string {
  return rustIdentifier(toPascalCase(name), name);
}

/** A Rust string literal. */
export function rustString(s: string): string {
  let out = '"';
  for (const ch of s) {
    const code = ch.codePointAt(0)!;
    if (ch === '"') out += '\\"';
    else if (ch === "\\") out += "\\\\";
    else if (ch === "\n") out += "\\n";
    else if (ch === "\r") out += "\\r";
    else if (ch === "\t") out += "\\t";
    else if (code < 0x20 || code === 0x7f) out += `\\u{${code.toString(16)}}`;
    else out += ch;
  }
  return out + '"';
}

/** A JSON value as a Rust expression of the runtime's Value. */
export function rustValue(v: unknown): string {
  if (v === null || v === undefined) return "rt::Value::Null";
  if (typeof v === "boolean") return `rt::Value::Bool(${v})`;
  if (typeof v === "number") {
    const text = JSON.stringify(v);
    return text === "null" ? "rt::Value::Null" : `rt::num(${rustString(text)})`;
  }
  if (typeof v === "string") return `rt::Value::from(${rustString(v)})`;
  if (Array.isArray(v)) return `rt::arr(vec![${v.map(rustValue).join(", ")}])`;
  const entries = Object.entries(v as Record<string, unknown>).filter(([, value]) => value !== undefined);
  return `rt::obj(vec![${entries.map(([k, value]) => `(${rustString(k)}, ${rustValue(value)})`).join(", ")}])`;
}

function rustStrings(items: string[]): string {
  return `vec![${items.map(rustString).join(", ")}]`;
}

const HEADER = "// Code generated by cli-contracts. DO NOT EDIT.\n";

function handlerOptionsType(cmd: SpecCommand): string {
  return `${rustType(cmd.id)}HandlerOptions`;
}

function handlerOptionField(type: SpecCommand["options"][number]["type"]): string {
  return type === "boolean" ? "Option<bool>" : type === "strings" ? "Option<Vec<String>>" : "Option<String>";
}

export function rustHandlerSignature(cmd: SpecCommand, optionsPath = ""): string {
  const params = ["&mut self"];
  for (const arg of cmd.arguments) {
    const type = arg.variadic ? "Vec<String>" : arg.required ? "String" : "Option<String>";
    params.push(`${rustSnake(arg.name)}: ${type}`);
  }
  params.push(`options: ${optionsPath}${handlerOptionsType(cmd)}`, "parent_opts: &rt::Object");
  return `fn ${rustSnake(cmd.id)}(${params.join(", ")}) -> ${cmd.llm ? "(i32, Option<String>)" : "i32"}`;
}

function renderDispatchArm(cmd: SpecCommand): string {
  const args = cmd.arguments.map((arg, i) =>
    arg.variadic ? `inv.args[${i}].values()` : arg.required ? `inv.args[${i}].value()` : `inv.args[${i}].optional()`,
  );
  const fields = cmd.options.map((opt) => {
    const accessor = opt.type === "boolean" ? "boolean" : opt.type === "strings" ? "strings" : "string";
    return `${rustSnake(opt.key)}: inv.opts.${accessor}(${rustString(opt.key)})`;
  });
  args.push(`${handlerOptionsType(cmd)} { ${fields.join(", ")} }`, "&inv.globals");
  const call = `h.${rustSnake(cmd.id)}(${args.join(", ")})`;
  return cmd.llm
    ? `        ${rustString(cmd.id)} => {\n            let (exit_code, prompt) = ${call};\n            rt::Outcome { exit_code, prompt }\n        }`
    : `        ${rustString(cmd.id)} => rt::Outcome { exit_code: ${call}, prompt: None },`;
}

function renderOption(opt: TreeOption): string {
  const fields = [`flags: ${rustString(opt.flags)}`];
  if (opt.short !== undefined) fields.push(`short: Some(${rustString(opt.short)})`);
  if (opt.long !== undefined) fields.push(`long: Some(${rustString(opt.long)})`);
  fields.push(`name: ${rustString(opt.name)}`, `key: ${rustString(opt.key)}`);
  fields.push(`kind: rt::OptionKind::${opt.kind === "flag" ? "Flag" : opt.kind === "negate" ? "Negate" : "TakesValue"}`);
  if (opt.variadic) fields.push("variadic: true");
  if (opt.version) fields.push("version: true");
  return `rt::CliOption { ${fields.join(", ")}, ..Default::default() }`;
}

function renderNode(node: TreeNode, indent: string): string {
  const i1 = indent + "    ";
  const fields = [`name: ${rustString(node.name)}`, `help: ${rustString(node.help)}`];
  if (node.options.length > 0) {
    fields.push(`options: vec![\n${node.options.map((o) => `${i1}    ${renderOption(o)},`).join("\n")}\n${i1}]`);
  }
  if (node.initialValues.length > 0) {
    fields.push(`initial_values: vec![${node.initialValues.map(([k, v]) => `(${rustString(k)}, ${rustValue(v)})`).join(", ")}]`);
  }
  if (node.arguments.length > 0) {
    fields.push(
      `arguments: vec![${node.arguments
        .map((a) => `rt::Argument { name: ${rustString(a.name)}, required: ${a.required}, variadic: ${a.variadic} }`)
        .join(", ")}]`,
    );
  }
  if (node.commands.length > 0) {
    fields.push(`commands: vec![\n${node.commands.map((c) => `${i1}    ${renderNode(c, i1 + "    ")},`).join("\n")}\n${i1}]`);
  }
  if (node.hidden) fields.push("hidden: true");
  if (node.defaultCommand !== undefined) fields.push(`default_command: Some(${rustString(node.defaultCommand)})`);
  if (node.helpCommand !== undefined) fields.push(`help_command: Some(${rustString(node.helpCommand)})`);
  if (node.helpShort !== undefined) fields.push(`help_short: Some(${rustString(node.helpShort)})`);
  if (node.helpLong !== undefined) fields.push(`help_long: Some(${rustString(node.helpLong)})`);
  if (node.action?.kind === "extract") {
    fields.push("action: Some(rt::Action::Extract)");
  } else if (node.action) {
    fields.push(
      `action: Some(rt::Action::Command { command_id: ${rustString(node.action.commandId)}, llm: ${node.action.llm}, introspect: ${node.action.introspect} })`,
    );
  }
  if (node.optionSuggestions.length > 0) fields.push(`option_suggestions: ${rustStrings(node.optionSuggestions)}`);
  if (node.commandSuggestions.length > 0) fields.push(`command_suggestions: ${rustStrings(node.commandSuggestions)}`);
  if (node.digitShortOption) fields.push("digit_short_option: true");
  return `rt::Command {\n${fields.map((f) => `${i1}${f},`).join("\n")}\n${i1}..Default::default()\n${indent}}`;
}

/** The contract's commands, one per id (a later command of the same id replaces an earlier one, as in TypeScript). */
function uniqueCommands(spec: RuntimeSpec): SpecCommand[] {
  return [...new Map(spec.commands.map((cmd) => [cmd.id, cmd])).values()];
}

function generateProgram(spec: RuntimeSpec): string {
  const commands = uniqueCommands(spec);
  const lines: string[] = [HEADER, "use cli_contracts_runtime as rt;", ""];

  for (const cmd of commands) {
    lines.push(`/// The options the program passes to the \`${cmd.id}\` handler, as given.`);
    lines.push("#[rustfmt::skip]");
    lines.push("#[derive(Debug, Clone, Default, PartialEq)]");
    lines.push(`pub struct ${handlerOptionsType(cmd)} {`);
    for (const opt of cmd.options) lines.push(`    pub ${rustSnake(opt.key)}: ${handlerOptionField(opt.type)},`);
    lines.push("}", "");
  }

  lines.push("/// Runs the contract's commands. A handler returns the exit code; a command");
  lines.push("/// that takes `--adapter` also returns the prompt it built, which the program");
  lines.push("/// writes with `--show-prompt`.");
  lines.push("#[rustfmt::skip]");
  lines.push("#[allow(clippy::too_many_arguments)]");
  lines.push("pub trait CommandHandlers {");
  for (const cmd of commands) lines.push(`    ${rustHandlerSignature(cmd)};`);
  lines.push("}", "");

  lines.push("/// The program: its command tree, run with the handlers.");
  lines.push("pub struct Program<H: CommandHandlers> {");
  lines.push("    program: rt::Program,");
  lines.push("    handlers: H,");
  lines.push("}", "");
  lines.push("#[rustfmt::skip]");
  lines.push("impl<H: CommandHandlers> Program<H> {");
  lines.push("    /// Creates the program. `version` is what `--version` writes.");
  lines.push("    pub fn new(handlers: H, version: &str, options: rt::ProgramOptions) -> Self {");
  lines.push("        let program = rt::Program {");
  lines.push("            root: tree(),");
  lines.push("            version: version.to_string(),");
  lines.push("            options,");
  lines.push(
    spec.policyDefinitions
      ? "            policy: super::policy::command_definitions().into_iter().map(|(id, def)| (id.to_string(), def)).collect(),"
      : "            policy: Default::default(),",
  );
  lines.push(`            extract: ${spec.extract ? "Some(extract_spec())" : "None"},`);
  lines.push("        };");
  lines.push("        Self { program, handlers }");
  lines.push("    }", "");
  lines.push("    /// Parses an invocation, runs what it names and returns the exit code.");
  lines.push("    pub fn run(&mut self, argv: &[String], stdout: &mut dyn std::io::Write, stderr: &mut dyn std::io::Write) -> i32 {");
  lines.push("        let handlers = &mut self.handlers;");
  lines.push("        self.program.run(argv, stdout, stderr, &mut |id: &str, inv: &rt::Invocation| dispatch(handlers, id, inv))");
  lines.push("    }", "");
  lines.push("    /// Runs the program with the process's arguments and exits with its exit code.");
  lines.push("    pub fn main(mut self) -> ! {");
  lines.push("        let argv: Vec<String> = std::env::args_os().skip(1).map(|a| a.to_string_lossy().into_owned()).collect();");
  lines.push("        let code = self.run(&argv, &mut std::io::stdout(), &mut std::io::stderr());");
  lines.push("        std::process::exit(code)");
  lines.push("    }", "");
  lines.push("    pub fn handlers(&self) -> &H {");
  lines.push("        &self.handlers");
  lines.push("    }", "");
  lines.push("    pub fn handlers_mut(&mut self) -> &mut H {");
  lines.push("        &mut self.handlers");
  lines.push("    }");
  lines.push("}", "");

  lines.push("#[rustfmt::skip]");
  lines.push("fn dispatch<H: CommandHandlers>(h: &mut H, id: &str, inv: &rt::Invocation) -> rt::Outcome {");
  lines.push("    match id {");
  for (const cmd of commands) lines.push(renderDispatchArm(cmd));
  lines.push('        _ => unreachable!("the tree names only the contract\'s commands"),');
  lines.push("    }", "}", "");

  lines.push("#[rustfmt::skip]");
  lines.push("fn tree() -> rt::Command {");
  lines.push(`    ${renderNode(spec.tree, "    ")}`);
  lines.push("}", "");

  if (spec.extract) {
    const x = spec.extract;
    lines.push("#[rustfmt::skip]");
    lines.push("fn extract_spec() -> rt::ExtractSpec {");
    lines.push("    rt::ExtractSpec {");
    lines.push(`        yaml_with_meta: ${rustString(x.yamlWithMeta)},`);
    lines.push(`        yaml_without_meta: ${rustString(x.yamlWithoutMeta)},`);
    lines.push(`        json_with_meta: ${rustString(x.jsonWithMeta)},`);
    lines.push(`        json_without_meta: ${rustString(x.jsonWithoutMeta)},`);
    lines.push(`        filter_head: ${rustString(x.filter.head)},`);
    lines.push(`        filter_tail: ${rustString(x.filter.tail)},`);
    lines.push("        sets: vec![");
    for (const set of x.filter.sets) {
      lines.push(
        `            rt::ExtractSet { id: ${rustString(set.id)}, key: ${rustString(set.key)}, before: ${rustStrings(set.before)}, after: ${rustStrings(set.after)}, commands: vec![${set.commands.map((c) => `(${rustString(c.id)}, ${rustString(c.text)})`).join(", ")}] },`,
      );
    }
    lines.push("        ],", "    }", "}", "");
  }
  return lines.join("\n");
}

function generatePolicy(spec: RuntimeSpec): string {
  const lines = [HEADER, "use cli_contracts_runtime as rt;", ""];
  lines.push("/// By command id, the part of each command's contract its policy is derived from.");
  lines.push("#[rustfmt::skip]");
  lines.push("pub fn command_definitions() -> Vec<(&'static str, rt::Value)> {");
  lines.push("    vec![");
  for (const [id, def] of spec.policyDefinitions!) lines.push(`        (${rustString(id)}, ${rustValue(def)}),`);
  lines.push("    ]", "}", "");
  lines.push("/// Derives a command's policy from its option values, keyed as the program");
  lines.push("/// keys them (`dry-run` -> `dryRun`).");
  lines.push("#[rustfmt::skip]");
  lines.push("pub fn derive_command_policy(command_id: &str, option_values: &rt::Object) -> Result<rt::Value, String> {");
  lines.push("    let definition = command_definitions()");
  lines.push("        .into_iter()");
  lines.push("        .rev()");
  lines.push("        .find(|(id, _)| *id == command_id)");
  lines.push('        .ok_or_else(|| format!("Unknown command: {command_id}"))?');
  lines.push("        .1;");
  lines.push("    Ok(rt::introspect(command_id, &definition, option_values))");
  lines.push("}", "");
  return lines.join("\n");
}

function generateContract(spec: RuntimeSpec): string {
  return [
    HEADER,
    "/// The contract the program was generated from.",
    "#[rustfmt::skip]",
    `pub const CONTRACT_YAML: &str = ${rustString(spec.contract!.yaml)};`,
    "",
    "/// The contract as JSON.",
    "#[rustfmt::skip]",
    `pub const CONTRACT_JSON: &str = ${rustString(spec.contract!.json)};`,
    "",
  ].join("\n");
}

export function generateRust(ctx: NormalizedContext, options: RustGeneratorOptions = {}): Record<string, string> {
  const spec = buildRuntimeSpec(ctx, options.contractYaml);
  const output: Record<string, string> = { "program.rs": generateProgram(spec) };
  const modules = ["program"];
  if (spec.policyDefinitions) {
    output["policy.rs"] = generatePolicy(spec);
    modules.push("policy");
  }
  if (spec.contract) {
    output["contract.rs"] = generateContract(spec);
    modules.push("contract");
  }
  modules.sort();
  output["mod.rs"] = [HEADER, ...modules.map((m) => `pub mod ${m};`), "", "pub use program::*;", ""].join("\n");
  return output;
}
